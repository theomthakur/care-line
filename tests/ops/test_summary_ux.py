"""Post-call summary, abandoned-call closing, privacy of the list, and no-store headers.

Real core app + ops, one shared SQLite file, driven through core's own agent routes."""

from __future__ import annotations

from datetime import timedelta

import pytest

from backend.ops import summary as ops_summary
from tests.ops.test_concurrent_calls import KEY, Caller, clk, web  # noqa: F401


def summary_of(web, call):
    r = web.get(f"/calls/{call.id}/summary")
    assert r.status_code == 200, r.text
    return r.json()


def booked_call(web, clk, room="booked"):
    c = Caller(web, clk, room)
    c.turn("user", "I need a new primary care doctor near 10023.")
    c.verify("4417", 4)
    c.search()
    slots = c.choose("P2")
    c.read_back(slots[0]["slot_id"])
    conf = c.book()
    return c, conf


def test_finalized_booking_summary_is_structured_and_survives_reopen(web, clk):
    c, conf = booked_call(web, clk)
    assert c.post("finalize").status_code == 200
    body = summary_of(web, c)
    assert body["summary"]["outcome"] == "booked"
    d = body["details"]
    assert d["verification"] == "verified"
    assert d["appointment"]["confirmation"] == conf
    assert d["provider"]["name"] == d["appointment"]["doctor"]
    assert d["problems"] == [] and d["follow_ups"] == []
    assert "No action needed" in d["next_action"]
    # reopening later returns the same stored summary: nothing is regenerated by a model
    assert summary_of(web, c) == body
    # the State contract object is untouched by the new endpoint
    assert "details" not in web.get(f"/calls/{c.id}/state").json()["state"]["summary"]


def test_failed_booking_with_followup_reports_followup_and_next_action(web, clk):
    c = Caller(web, clk, "followup")
    c.turn("user", "I need a doctor but I can't pick a time.")
    c.verify("4417", 4)
    c.search()
    c.followup("Please call me to help choose a visit time.")
    c.post("finalize")
    body = summary_of(web, c)
    assert body["summary"]["outcome"] == "followup"
    d = body["details"]
    assert d["appointment"] is None
    assert len(d["follow_ups"]) == 1 and d["follow_ups"][0]["status"] == "open"
    assert d["follow_ups"][0]["reference"] in d["next_action"]
    # completing the task changes the facts read on the next open, not the stored outcome
    tid = web.get(f"/calls/{c.id}/state").json()["state"]["tasks"][0]["task_id"]
    assert web.post(f"/tasks/{tid}/complete", json={}).status_code == 200
    again = summary_of(web, c)
    assert again["details"]["follow_ups"][0]["status"] == "completed"
    assert "No action needed" in again["details"]["next_action"]


def test_call_with_nothing_done_is_not_completed_and_never_claims_a_booking(web, clk):
    c = Caller(web, clk, "silent")
    c.turn("user", "Hello?")
    c.post("finalize")
    body = summary_of(web, c)
    assert body["summary"]["outcome"] == "not_completed"
    assert body["details"]["verification"] == "not_attempted"
    assert body["details"]["appointment"] is None
    assert "booked" not in body["summary"]["text"].lower().replace("no booking", "")


def test_failed_verification_is_reported_as_a_problem(web, clk):
    c = Caller(web, clk, "wrong")
    c.turn("user", "Book me a doctor.")
    r = c.post("verify", {"member_digits": "0000", "birth_month": 1})
    assert r.status_code != 200
    d = summary_of(web, c)["details"]
    assert d["verification"] == "failed"
    assert any("did not match" in p for p in d["problems"])


